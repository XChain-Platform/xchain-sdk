// Regenerate src/contract/templates.js from the canonical xchain-contracts
// sources (templates + patterns), base64-embedded so sdk.scaffold() can return
// them in a browser bundle without fs at runtime. Re-run after any template or
// pattern change:  npm run sync:templates
//
// A drift guard (test/unit/template-parity.test.js) fails the build if the
// embedded copy and the canonical xchain-contracts source diverge.

'use strict';

const fs   = require('fs');
const path = require('path');

const SDK_ROOT       = path.join(__dirname, '..');
const CONTRACTS_DIR  = path.join(SDK_ROOT, '..', 'xchain-contracts');
const OUT_FILE       = path.join(SDK_ROOT, 'src', 'contract', 'templates.js');

const TEMPLATE_NAMES = ['escrow', 'vesting', 'crowdsale', 'amm'];

function b64(file) {
    return Buffer.from(fs.readFileSync(file, 'utf8'), 'utf8').toString('base64');
}

function collectTemplates() {
    const out = {};
    for (const name of TEMPLATE_NAMES) {
        const f = path.join(CONTRACTS_DIR, name, name + '.js');
        if (!fs.existsSync(f)) throw new Error('missing template source: ' + f);
        out[name] = b64(f);
    }
    return out;
}

function collectPatterns() {
    const dir = path.join(CONTRACTS_DIR, 'patterns');
    const out = {};
    if (!fs.existsSync(dir)) return out;
    for (const f of fs.readdirSync(dir).sort()) {
        if (!f.endsWith('.js') || f.endsWith('.test.js')) continue;
        out[f.replace(/\.js$/, '')] = b64(path.join(dir, f));
    }
    return out;
}

function render(templates, patterns) {
    // Deterministic, stable formatting so re-running produces no diff.
    const block = (obj) => Object.keys(obj)
        .map((k) => '        ' + JSON.stringify(k) + ': ' + JSON.stringify(obj[k]))
        .join(',\n');
    return [
        '// Copyright © 2025–2026 Dankest, LLC',
        '// SPDX-License-Identifier: AGPL-3.0-or-later',
        '//',
        '// GENERATED by scripts/sync-templates.js. DO NOT EDIT BY HAND.',
        '// Re-run `npm run sync:templates` after changing any xchain-contracts source.',
        '//',
        '// Each value is the base64-encoded UTF-8 source of a canonical xchain-contracts',
        '// template/pattern, embedded so sdk.scaffold() works in a browser bundle (no fs).',
        '// A drift guard (test/unit/template-parity.test.js) enforces byte-parity with the',
        '// xchain-contracts repo.',
        '',
        'module.exports = {',
        '    templates: {',
        block(templates),
        '    },',
        '    patterns: {',
        block(patterns),
        '    }',
        '};',
        ''
    ].join('\n');
}

function main() {
    if (!fs.existsSync(CONTRACTS_DIR))
        throw new Error('xchain-contracts sibling repo not found at ' + CONTRACTS_DIR);
    const templates = collectTemplates();
    const patterns  = collectPatterns();
    fs.writeFileSync(OUT_FILE, render(templates, patterns));
    const t = Object.keys(templates).length, p = Object.keys(patterns).length;
    process.stdout.write('synced ' + t + ' templates + ' + p + ' patterns -> src/contract/templates.js\n');
}

main();
